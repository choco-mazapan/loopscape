# ---- wallpaper tiles (Tile1 = rotate, full width; then day and night grids) ----
A '; ----- wallpaper style tiles (settings.lua: TILES list, TileBaseN = selected / normal) -----'
function Tile($n, $text, $x, $y, $w) {
  A "[MeterTile$n]"; A 'Meter=String'; A 'MeterStyle=StyleText | StyleTile'; A 'Group=TabWallpaper'
  A "Text=$text"; A "X=$x"; A "Y=$y"; if ($w) { A "W=$w" }
  A "SolidColor=[#TileBase$n]"; A "FontColor=[#TileFont$n]"
  A "MouseOverAction=[!SetOption MeterTile$n SolidColor #ColorTileHover#][!UpdateMeter MeterTile$n][!CommandMeasure MeasureSettings `"Hover($n)`"]"
  A "MouseLeaveAction=[!SetOption MeterTile$n SolidColor `"[#*TileBase$n*]`"][!UpdateMeter MeterTile$n][!CommandMeasure MeasureSettings `"Hover(0)`"]"
  A "LeftMouseUpAction=[!CommandMeasure MeasureSettings `"PickTile($n)`"]"
  if ($n -gt 1) { A "RightMouseUpAction=[!CommandMeasure MeasureSettings `"ToggleExclude($n)`"]" }
  A ''
}
